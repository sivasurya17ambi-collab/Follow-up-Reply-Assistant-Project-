"""
Export Service for Drafts (Text, Markdown, HTML, EML, JSON)
Project Code: PRJ-042 | Follow-up Reply Assistant
"""

import json
import re
from datetime import datetime
from email.message import EmailMessage
from typing import Dict, Any, Tuple

class ExportService:
    """Formats and exports email drafts into various standard formats."""

    @staticmethod
    def to_plain_text(subject: str, recipient: str, body: str, sender: str = "Sivasurya B") -> Tuple[str, str, str]:
        content = (
            f"TO: {recipient}\n"
            f"FROM: {sender}\n"
            f"DATE: {datetime.now().strftime('%a, %d %b %Y %H:%M:%S')}\n"
            f"SUBJECT: {subject}\n"
            f"{'='*60}\n\n"
            f"{body}\n\n"
            f"{'='*60}\n"
            f"Generated via Follow-up Reply Assistant (PRJ-042)\n"
        )
        safe_name = re.sub(r"[^\w\-]", "_", subject[:30]).strip("_")
        filename = f"draft_{safe_name}.txt"
        return filename, content, "text/plain"

    @staticmethod
    def to_markdown(subject: str, recipient: str, body: str, sender: str = "Sivasurya B") -> Tuple[str, str, str]:
        content = (
            f"# Email Draft: {subject}\n\n"
            f"- **To:** {recipient}\n"
            f"- **From:** {sender}\n"
            f"- **Date:** {datetime.now().strftime('%B %d, %Y %H:%M')}\n"
            f"- **Status:** Ready for Dispatch\n\n"
            f"---\n\n"
            f"{body}\n\n"
            f"---\n"
            f"*Generated by [Follow-up Reply Assistant](PRJ-042)*\n"
        )
        safe_name = re.sub(r"[^\w\-]", "_", subject[:30]).strip("_")
        filename = f"draft_{safe_name}.md"
        return filename, content, "text/markdown"

    @staticmethod
    def to_html(subject: str, recipient: str, body: str, sender: str = "Sivasurya B") -> Tuple[str, str, str]:
        # Convert newlines and basic markdown to HTML
        html_body = body.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        html_body = re.sub(r"###\s+([^\n]+)", r"<h3 style='color: #1e3a8a; margin-top: 18px; margin-bottom: 8px;'>\1</h3>", html_body)
        html_body = re.sub(r"•\s+([^\n]+)", r"<li style='margin-bottom: 4px;'>\1</li>", html_body)
        html_body = re.sub(r"(\d+\.\s+[^\n]+)", r"<li style='margin-bottom: 4px;'>\1</li>", html_body)
        html_body = html_body.replace("\n\n", "<br/><br/>").replace("\n", "<br/>")

        content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>{subject}</title>
    <style>
        body {{
            font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif;
            background-color: #f1f5f9;
            margin: 0;
            padding: 24px;
            color: #334155;
        }}
        .email-container {{
            max-width: 680px;
            margin: 0 auto;
            background-color: #ffffff;
            border-radius: 8px;
            box-shadow: 0 4px 6px -1px rgba(0, 0, 0, 0.1), 0 2px 4px -1px rgba(0, 0, 0, 0.06);
            overflow: hidden;
            border: 1px solid #e2e8f0;
        }}
        .header {{
            background: linear-gradient(135deg, #1e40af, #3b82f6);
            color: #ffffff;
            padding: 20px 24px;
        }}
        .header h2 {{ margin: 0 0 6px 0; font-size: 20px; }}
        .header-meta {{ font-size: 13px; opacity: 0.9; }}
        .content {{
            padding: 24px;
            line-height: 1.6;
            font-size: 15px;
        }}
        .footer {{
            background-color: #f8fafc;
            padding: 14px 24px;
            border-top: 1px solid #e2e8f0;
            font-size: 12px;
            color: #64748b;
            text-align: center;
        }}
    </style>
</head>
<body>
    <div class="email-container">
        <div class="header">
            <h2>{subject}</h2>
            <div class="header-meta">
                <strong>To:</strong> {recipient} &nbsp;|&nbsp; <strong>From:</strong> {sender}
            </div>
        </div>
        <div class="content">
            {html_body}
        </div>
        <div class="footer">
            Follow-up Reply Assistant (Project PRJ-042) &bull; SIVASURYA.B PSVPEC (411723205052)
        </div>
    </div>
</body>
</html>"""
        safe_name = re.sub(r"[^\w\-]", "_", subject[:30]).strip("_")
        filename = f"draft_{safe_name}.html"
        return filename, content, "text/html"

    @staticmethod
    def to_eml(subject: str, recipient: str, body: str, sender: str = "Sivasurya B") -> Tuple[str, str, str]:
        """RFC 822 EML format that opens natively in Outlook, Apple Mail, and Thunderbird."""
        msg = EmailMessage()
        msg["Subject"] = subject
        msg["From"] = f"{sender} <sivasurya.b.27.it@psvpec.in>"
        msg["To"] = recipient
        msg["Date"] = datetime.now().strftime("%a, %d %b %Y %H:%M:%S +0000")
        msg["X-Mailer"] = "Follow-up Reply Assistant (PRJ-042)"
        msg.set_content(body)

        safe_name = re.sub(r"[^\w\-]", "_", subject[:30]).strip("_")
        filename = f"draft_{safe_name}.eml"
        return filename, msg.as_string(), "message/rfc822"

    @staticmethod
    def to_json(subject: str, recipient: str, body: str, sender: str = "Sivasurya B") -> Tuple[str, str, str]:
        data = {
            "project_code": "PRJ-042",
            "subject": subject,
            "recipient": recipient,
            "sender": sender,
            "body": body,
            "generated_at": datetime.now().isoformat(),
            "status": "send_ready"
        }
        content = json.dumps(data, indent=2)
        safe_name = re.sub(r"[^\w\-]", "_", subject[:30]).strip("_")
        filename = f"draft_{safe_name}.json"
        return filename, content, "application/json"

    def export(self, subject: str, recipient: str, body: str, export_format: str, sender: str = "Sivasurya B") -> Dict[str, str]:
        fmt = export_format.lower().strip()
        if fmt == "txt":
            fname, content, mime = self.to_plain_text(subject, recipient, body, sender)
        elif fmt in ["md", "markdown"]:
            fname, content, mime = self.to_markdown(subject, recipient, body, sender)
        elif fmt == "html":
            fname, content, mime = self.to_html(subject, recipient, body, sender)
        elif fmt == "eml":
            fname, content, mime = self.to_eml(subject, recipient, body, sender)
        elif fmt == "json":
            fname, content, mime = self.to_json(subject, recipient, body, sender)
        else:
            fname, content, mime = self.to_plain_text(subject, recipient, body, sender)
            fmt = "txt"

        return {
            "format": fmt,
            "filename": fname,
            "content": content,
            "mime_type": mime
        }

export_service = ExportService()
